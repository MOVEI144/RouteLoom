#pragma once

// SDK v1 zero-touch join transport (docs/design/sdk-v1/02-zero-touch-join.md
// §5, §7; plan P3-1/P3-2). Codecs and bounded buffers only — the engines
// that use them are in sdkv1_join_relay.hpp.
//
//   RLD1 body v3 (class ZeroTouch=3)   DISCOVER 24 B (broadcast), OFFER 48 B
//   BootstrapAuth phases 4-6           EdhocMessage / Resume / RelayStatus,
//                                      assembled objects of at most 1024 B
//   join chunk / reply                 RLD1 kinds 5/6 and Wire FrameTypes 5/6
//   RelayHeader + relay object         Wire FrameTypes 3/4 (single frame) or
//                                      5/6 (chunked) between proxy and gateway
//
// All integers are big-endian, reserved bytes are zero, every length is
// exact, and the byte layouts are pinned by protocol/sdkv1-golden/
// join-transport/ (generated by the independent
// tools/gen_sdkv1_join_transport_vectors.py). Every codec is allocation-free;
// decoders borrow their byte views from the input.
//
// Resolved in implementation (02 §5.4 / §7.4 record the rationale):
//   - One EDHOC / RLRES1 message is at most kJoinMessageMax = 960 B, so the
//     RLD1 object (6 + 16 + 960), the relay object (24 + 960) and the USB
//     0x60/0x61 inner bodies (<= 1005 B, usb_host_ops.hpp) all fit their
//     1024 B ceilings with one constant.
//   - Chunks of both carriers share one layout: ver u8=1 | sub u8 |
//     id u32 | offset u16 | total u16 | data, where sub = (phase << 4) |
//     step names the message (0x41..0x45 EDHOC, 0x51..0x53 RLRES1) — so a
//     retransmitted chunk of a completed object never reads as the next
//     object — and id is the first four nonce bytes on RLD1, the relay_id on
//     Wire. Offsets sit on the carrier's chunk grid (106 B RLD1, 118 B Wire)
//     and only objects above the carrier's single-frame limit are chunked.
//   - RelayHeader byte 23 (reserved in 02 §7.1) carries the BootstrapAuth
//     phase (4 EDHOC, 5 RLRES1), because `step` alone is ambiguous.

