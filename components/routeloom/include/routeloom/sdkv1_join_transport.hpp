// ===================================================================================
// BootstrapAuth phases 4-6 (02 §5.3) — the assembled join object
// ===================================================================================
enum class JoinAuthPhase : std::uint8_t {
  EdhocMessage = 4,  // step 1..4 = EDHOC message_1..4, 5 = EDHOC error
  Resume = 5,        // step 1..3 = RLRES1 R1..R3 (06 §2.1)
  RelayStatus = 6,   // step 1, proxy -> device, unauthenticated hint
};
constexpr std::uint8_t kJoinEdhocErrorStep = 5;

enum class RelayStatusCode : std::uint8_t {
  Queued = 1,
  AuthorityUnreachable = 2,
  Busy = 3,
  Aborted = 4,
};

// Object layout (<= 1024 B):
//   0 u8 version = 1 | 1 u8 phase | 2 u8 step | 3 u8 reserved = 0   (BA prefix)
//   phase 4/5: 4 u8 cookie_echo_present | 5 u8 reserved = 0 | [cookie 16B] |
//              message 1..960 B
//     cookie_echo_present is 1 exactly for phase 4 step 1 (m1); phase 5
//     step 1 (R1) may carry it (0/1, the carrier policy decides), every
//     other step carries 0.
//   phase 6:   4 u8 status (1..4) | 5 u32 retry_after_ms (<= 600000) — 9 B
constexpr std::size_t kJoinAuthPrefixSize = autonomy::kBootstrapAuthHeaderSize;  // 4
constexpr std::size_t kJoinObjectHeadSize = kJoinAuthPrefixSize + 2;               // 6
constexpr std::size_t kRelayStatusObjectSize = kJoinAuthPrefixSize + 5;            // 9
static_assert(kJoinObjectHeadSize + kJoinCookieSize + kJoinMessageMax <= kJoinObjectMax,
              "largest RLD1 join object fits the 1024 B assembly ceiling");

struct JoinAuthObject {
  JoinAuthPhase phase{JoinAuthPhase::EdhocMessage};
  std::uint8_t step{1};
  bool cookie_present{false};
  JoinCookieBytes cookie{};
  ByteView message{};  // phase 4/5
  RelayStatusCode relay_status{RelayStatusCode::Queued};  // phase 6
  std::uint32_t retry_after_ms{0};                         // phase 6
};

using JoinObjectBytes = ByteBuffer<kJoinObjectMax>;

bool join_step_valid(JoinAuthPhase phase, std::uint8_t step) noexcept;
Status join_object_validate(const JoinAuthObject& object) noexcept;
std::size_t join_object_encoded_size(const JoinAuthObject& object) noexcept;
Status join_object_encode(const JoinAuthObject& object, MutableByteView out,
                          std::size_t& written) noexcept;
Status join_object_decode(ByteView encoded, JoinAuthObject& out) noexcept;

// Which way a join step flows on the device <-> proxy hop.
enum class JoinFlow : std::uint8_t {
  Up = 1,      // device -> proxy (-> authority)
  Down = 2,    // proxy -> device (authority -> device, or a proxy hint)
  Either = 3,  // EDHOC error (step 5): either end may abort
};
JoinFlow join_step_flow(JoinAuthPhase phase, std::uint8_t step) noexcept;

// ===================================================================================
// Chunks and replies (RLD1 kinds 5/6, Wire FrameTypes 5/6)
// ===================================================================================
enum class JoinCarrier : std::uint8_t {
  Rld1 = 0,       // device <-> proxy, 1 hop, 116 B bodies
  WireRelay = 1,  // proxy <-> gateway, member links, 128 B payloads
};

constexpr std::uint8_t kJoinChunkVersion = 1;
constexpr std::size_t kJoinChunkHeaderSize = 10;
constexpr std::size_t kJoinReplySize = 10;
constexpr std::size_t kRld1JoinChunkData = autonomy::kRld1MaxBody - kJoinChunkHeaderSize;  // 106
constexpr std::size_t kWireRelayChunkData = kMaxApplicationPayload - kJoinChunkHeaderSize;  // 118
constexpr std::size_t kJoinChunkBitmapBits = 16;

constexpr std::size_t join_single_frame_max(const JoinCarrier carrier) noexcept {
  return carrier == JoinCarrier::Rld1 ? autonomy::kRld1MaxBody : kMaxApplicationPayload;
}
constexpr std::size_t join_chunk_data_max(const JoinCarrier carrier) noexcept {
  return carrier == JoinCarrier::Rld1 ? kRld1JoinChunkData : kWireRelayChunkData;
}
constexpr std::size_t join_chunk_count(const JoinCarrier carrier, const std::size_t total) noexcept {
  return (total + join_chunk_data_max(carrier) - 1) / join_chunk_data_max(carrier);
}
static_assert(join_chunk_count(JoinCarrier::Rld1, kJoinObjectMax) <= kJoinChunkBitmapBits,
              "RLD1 chunk grid fits the receipt bitmap");
static_assert(join_chunk_count(JoinCarrier::WireRelay, kJoinObjectMax) <= kJoinChunkBitmapBits,
              "Wire chunk grid fits the receipt bitmap");

// sub = (phase << 4) | step for phases 4 and 5 (a RelayStatus is 9 B and
// never chunked). The legacy dev-PSK chunk uses sub 1, so the two never mix.
constexpr std::uint8_t join_sub(const JoinAuthPhase phase, const std::uint8_t step) noexcept {
  return static_cast<std::uint8_t>((static_cast<std::uint8_t>(phase) << 4U) | step);
}
bool join_sub_decode(std::uint8_t sub, JoinAuthPhase& phase, std::uint8_t& step) noexcept;

// Object lane (G-SEC P4 §7.3): join-relay objects and member end-session
// objects share the Wire chunk/reply carriers (FrameTypes 5/6) but never an
// assembly. The lane bit lives in the sub byte, so the slot's (carrier,
// sub, id) key already separates the lanes and join golden bytes stay
// identical. End chunks never ride RLD1.
enum class ObjectLane : std::uint8_t { JoinRelay = 0, EndSession = 1 };
// end_sub = 0x80 | (phase << 4) | step, phases 4/5 only: 0xC1..0xC4 and
// 0xD1..0xD3. Member EDHOC has no step-5 error object.
constexpr std::uint8_t kEndSubLaneBit = 0x80;
constexpr std::uint8_t end_sub(const JoinAuthPhase phase, const std::uint8_t step) noexcept {
  return static_cast<std::uint8_t>(kEndSubLaneBit | join_sub(phase, step));
}
constexpr std::uint8_t object_sub(const ObjectLane lane, const JoinAuthPhase phase,
                                  const std::uint8_t step) noexcept {
  return lane == ObjectLane::EndSession ? end_sub(phase, step) : join_sub(phase, step);
}
bool object_sub_decode(std::uint8_t sub, ObjectLane& lane, JoinAuthPhase& phase,
                       std::uint8_t& step) noexcept;
// RLD1: the chunk id is the first four transaction-nonce bytes (big-endian).
std::uint32_t join_rld1_object_id(const JoinNonce& nonce) noexcept;

// Chunk: 0 u8 ver = 1 | 1 u8 sub | 2 u32 id (nonzero) | 6 u16 offset |
//        8 u16 total | 10 data
//   total > join_single_frame_max(carrier) and <= 1024; offset = k * grid;
//   data length = min(grid, total - offset), exactly.
struct JoinChunk {
  JoinAuthPhase phase{JoinAuthPhase::EdhocMessage};
  std::uint8_t step{1};
  std::uint32_t id{0};
  std::uint16_t offset{0};
  std::uint16_t total{0};
  ByteView data{};
  ObjectLane lane{ObjectLane::JoinRelay};
};

// Reply: 0 u8 ver = 1 | 1 u8 sub | 2 u32 id | 6 u16 received | 8 u8 status |
//        9 u8 reserved = 0   (10 B, 02 §5.3)
//   received = contiguous prefix held by the receiver; Complete carries the
//   object's total. Aborted asks the sender to restart the object.
enum class JoinReplyStatus : std::uint8_t {
  Progress = 0,
  Complete = 1,
  Aborted = 2,
};
struct JoinReply {
  JoinAuthPhase phase{JoinAuthPhase::EdhocMessage};
  std::uint8_t step{1};
  std::uint32_t id{0};
  std::uint16_t received{0};
  JoinReplyStatus status{JoinReplyStatus::Progress};
  ObjectLane lane{ObjectLane::JoinRelay};
};

Status join_chunk_encode(JoinCarrier carrier, const JoinChunk& chunk, MutableByteView out,
                         std::size_t& written) noexcept;
Status join_chunk_decode(JoinCarrier carrier, ByteView encoded, JoinChunk& out) noexcept;
Status join_reply_encode(const JoinReply& reply, MutableByteView out,
                         std::size_t& written) noexcept;
Status join_reply_decode(ByteView encoded, JoinReply& out) noexcept;

// --- Bounded object slot -----------------------------------------------------------
// One 1024 B buffer that holds EITHER an inbound assembly OR an outbound
// object awaiting its receiver's Complete reply. Chunks land on the fixed
// grid in any order; an exact duplicate is re-acknowledged, a chunk whose
// bytes differ from the held ones (or whose total changes) aborts the
// assembly (Conflict), a chunk of another object while one is assembling is
// refused (Busy), and an assembly older than its timeout is discarded. After
// Complete the slot remembers the object key so a late duplicate chunk
// re-sends the Complete reply instead of starting over — also while the
// slot already sends another object (only reset() forgets it).
class JoinObjectSlot {
 public:
  enum class Mode : std::uint8_t { Idle = 0, Assembling, Assembled, Sending };
  enum class Outcome : std::uint8_t {
    Progress = 0,  // stored (or exact duplicate): send `reply`
    Complete,      // whole object held: send `reply`, then read assembled()
    Repeat,        // duplicate chunk of the object completed last: re-send Complete
    Conflict,      // differing bytes / total: assembly dropped, reply Aborted
    Busy,          // another object is assembling or sending: dropped, no reply
    Rejected,      // chunk does not belong here (bad key/total): dropped
  };
  struct Accepted {
    Outcome outcome{Outcome::Rejected};
    JoinReply reply{};
    bool send_reply{false};
  };
  enum class ReplyOutcome : std::uint8_t {
    Ignored = 0,  // not for the object being sent
    Progress,     // receiver progress recorded
    Done,         // receiver holds the whole object; slot is Idle again
    Restart,      // receiver aborted: every chunk is due again
  };

  Mode mode() const noexcept { return mode_; }
  void reset() noexcept;

  // --- inbound
  Accepted accept(JoinCarrier carrier, const JoinChunk& chunk, MonotonicMs now_ms) noexcept;
  // Valid in Assembled until reset()/load()/the next accept of a new object.
  ByteView assembled() const noexcept;
  JoinAuthPhase phase() const noexcept { return phase_; }
  std::uint8_t step() const noexcept { return step_; }
  std::uint32_t id() const noexcept { return id_; }
  ObjectLane lane() const noexcept { return lane_; }
  // Wipes the buffer and returns to Idle in any mode, keeping the key of
  // the object completed last for Repeat detection (the owner consumed or
  // converted the object).
  void release_assembled() noexcept;
  // Occupant tag: bumped on every mode change, so a value captured before
  // a callback still names the occupant that was current then.
  std::uint32_t generation() const noexcept { return generation_; }
  // release_assembled() only while the slot still holds the occupant that
  // `expected` names — a callback that re-entered the owner (a fresh send,
  // a close, a new assembly) is left alone.
  void release_assembled_if(std::uint32_t expected) noexcept;

  // --- outbound
  // Copies `object` (> the carrier's single-frame limit, <= 1024 B) and
  // marks every chunk due. The caller emits chunk_at(i) for due chunks.
  // `lane` selects the chunk sub namespace (P4 §7.3); the default keeps the
  // join-relay 0x41..0x53 bytes. End objects never load on Rld1.
  Status load(JoinCarrier carrier, JoinAuthPhase phase, std::uint8_t step, std::uint32_t id,
              ByteView object, MonotonicMs now_ms,
              ObjectLane lane = ObjectLane::JoinRelay) noexcept;
  // In-place variant: the object was built in writable_buffer() already.
  Status load_in_place(JoinCarrier carrier, JoinAuthPhase phase, std::uint8_t step,
                       std::uint32_t id, std::size_t size, MonotonicMs now_ms,
                       ObjectLane lane = ObjectLane::JoinRelay) noexcept;
  MutableByteView writable_buffer() noexcept { return MutableByteView{data_.data(), data_.size()}; }
  std::size_t chunk_total() const noexcept;
  Status chunk_at(std::size_t index, JoinChunk& out) const noexcept;
  // Chunks the receiver has not confirmed (bit i = chunk i).
  std::uint16_t pending_mask() const noexcept;
  ReplyOutcome on_reply(const JoinReply& reply, MonotonicMs now_ms) noexcept;
  // Retransmission bookkeeping for Sending: marks the send time; the owner
  // decides when to retransmit (last_send_ms + interval) and gives up after
  // its own attempt budget.
  void note_sent(MonotonicMs now_ms) noexcept;
  MonotonicMs last_send_ms() const noexcept { return last_send_ms_; }
  std::uint8_t sends() const noexcept { return sends_; }

  // --- timing
  MonotonicMs started_ms() const noexcept { return started_ms_; }
  // Drops an Assembling object older than `timeout_ms`. True if dropped.
  bool expire(MonotonicMs now_ms, std::uint32_t timeout_ms) noexcept;

 private:
  // Drops the current assembly but keeps the completed-object memory.
  void drop_keep_completed() noexcept;
  std::uint16_t full_mask() const noexcept;
  std::uint16_t contiguous() const noexcept;

  std::array<std::uint8_t, kJoinObjectMax> data_{};
  Mode mode_{Mode::Idle};
  JoinCarrier carrier_{JoinCarrier::Rld1};
  ObjectLane lane_{ObjectLane::JoinRelay};
  JoinAuthPhase phase_{JoinAuthPhase::EdhocMessage};
  std::uint8_t step_{0};
  std::uint32_t id_{0};
  std::uint16_t total_{0};
  std::uint16_t have_{0};  // inbound: received chunks; outbound: confirmed chunks
  MonotonicMs started_ms_{0};
  MonotonicMs last_send_ms_{0};
  std::uint8_t sends_{0};
  // Bumped on every mode change: separates the occupant a callback saw
  // from one a reentrant call installed (see release_assembled_if).
  std::uint32_t generation_{0};
  // Last completed inbound object (Repeat detection).
  bool completed_valid_{false};
  JoinCarrier completed_carrier_{JoinCarrier::Rld1};
  std::uint8_t completed_sub_{0};
  std::uint32_t completed_id_{0};
  std::uint16_t completed_total_{0};
};

// ===================================================================================
// Wire relay object (02 §7.1): RelayHeader 24 B + message
// ===================================================================================
enum class RelayDirection : std::uint8_t { Up = 1, Down = 2 };
enum class RelayState : std::uint8_t {
  Continue = 0,  // more messages follow
  Final = 1,     // down only: last message of the exchange; the proxy frees its slot
  Abort = 2,     // either way: body is the 5 B RelayAbortBody
};

// RelayHeader (24 B):
//   0 u8 ver = 1 | 1 u8 dir (1 up, 2 down) | 2 u32 relay_id (nonzero)
//   6 u64 proxy NodeId | 14 6B joiner MAC (observed by the proxy)
//  20 u8 step | 21 u8 status (RelayState) | 22 i8 joiner_rssi_dbm (up only,
//     <= 0; down 0) | 23 u8 phase (4 EDHOC, 5 RLRES1)
// Body rules:
//   up   Continue  EDHOC steps 1/3/5, RLRES1 steps 1/3; message 1..960 B
//   down Continue  EDHOC step 2, RLRES1 step 2;         message 1..960 B
//   down Final     EDHOC steps 4/5, RLRES1 step 2;       message 1..960 B
//   Abort          any valid step of the phase; body = RelayAbortBody
//                  (up: status Aborted; down: AuthorityUnreachable/Busy/Aborted)
constexpr std::uint8_t kRelayVersion = 1;
constexpr std::size_t kRelayHeaderSize = 24;
constexpr std::size_t kRelayObjectMax = kRelayHeaderSize + kJoinMessageMax;  // 984
static_assert(kRelayObjectMax <= kJoinObjectMax, "relay object fits one object slot");

struct RelayHeader {
  RelayDirection dir{RelayDirection::Up};
  std::uint32_t relay_id{0};
  NodeId proxy{kInvalidNodeId};
  MacAddress joiner_mac{};
  JoinAuthPhase phase{JoinAuthPhase::EdhocMessage};
  std::uint8_t step{1};
  RelayState state{RelayState::Continue};
  std::int8_t joiner_rssi_dbm{0};
};

// Abort body (5 B): status u8 (RelayStatusCode) | retry_after_ms u32 (<= 600000).
constexpr std::size_t kRelayAbortBodySize = 5;
struct RelayAbortBody {
  RelayStatusCode status{RelayStatusCode::Aborted};
  std::uint32_t retry_after_ms{0};
};

struct RelayObject {
  RelayHeader header{};
  ByteView message{};       // Continue / Final
  RelayAbortBody abort{};   // Abort
};

Status relay_object_validate(const RelayObject& object) noexcept;
std::size_t relay_object_encoded_size(const RelayObject& object) noexcept;
Status relay_object_encode(const RelayObject& object, MutableByteView out,
                           std::size_t& written) noexcept;
Status relay_object_decode(ByteView encoded, RelayObject& out) noexcept;

// Single-frame carriage (object <= 128 B): up and down Continue ride Wire
// FrameType 3 (BootstrapAuth); down Final/Abort ride FrameType 4
// (MembershipResult) so the proxy releases its slot on the final type; an up
// Abort rides type 3. Larger objects ride FrameType 5 chunks (sub = phase/
// step, id = relay_id) acknowledged by FrameType 6 receipts.
FrameType relay_single_frame_type(const RelayHeader& header) noexcept;
Status relay_single_frame_decode(FrameType type, ByteView payload, RelayObject& out) noexcept;

// ===================================================================================
// Lane classification and admission (02 §4, §7.1, §9; 06-membership-admission §3-4)
// ===================================================================================
// RLD1 frames of the zero-touch / SDK v1 object lane: DISCOVER/OFFER body v3,
// BootstrapAuth phases 4-6, and chunks/replies whose sub is a phase-4/5 step.
// The owner hands them to the engine that owns the transaction nonce; legacy
// frames keep going to NeighborDiscovery unchanged.
bool zt_rld1_frame(const autonomy::Rld1Envelope& env) noexcept;

// RLD1 admission (after zt_rld1_frame): the local membership decides the
// role — a node that is not yet a member (Discovering/Authenticating) is the
// JOINER, a Member is a PROXY; nothing else talks on this lane.
//   joiner TX DISCOVER v3 (Discovering/Authenticating); RX OFFER v3;
//          Authenticating: TX up steps, RX down steps + RelayStatus, chunks of
//          up steps TX / down steps RX, replies the other way
//   proxy  RX DISCOVER v3; TX OFFER v3; RX up steps, TX down steps + RelayStatus;
//          chunks/replies accordingly. A Member never sends DISCOVER v3.
// A frame that does not parse far enough to classify is ProtocolError; a
// frame the role may not send/receive is AuthorizationFailed.
Status zt_admit_rld1(MembershipState local, AdmissionDirection direction,
                     const autonomy::Rld1Envelope& env) noexcept;

// Wire relay admission (02 §7.1): both ends are Members; only FrameTypes
// 3/4/5/6; a proxy exchanges relay frames with its configured gateway only;
// the gateway accepts relay frames from members and sends only to the proxy
// named in the object. `peer` is the verified mesh origin (RX) or
// destination (TX). Frames that are not relay frames are not this lane's.
Status zt_admit_relay(MembershipState local, bool local_is_gateway, AdmissionDirection direction,
                      FrameType type, NodeId peer, NodeId gateway) noexcept;

